// The website's planner (buildPlan/listStructure in site/index.html) against the shared fixtures;
// test/plan/run.lua checks the addon's Plan.lua against the same file, so both plan alike.
// Run: node --test test/plan/      Rewrite the fixtures after a planner change: UPDATE=1 node --test test/plan/
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const S = createRequire(import.meta.url)("../../site/sync.js");
const FIXTURE = new URL("./fixtures/plans.txt", import.meta.url);
const html = readFileSync(new URL("../../site/index.html", import.meta.url), "utf8");
const data = readFileSync(new URL("../../site/data.js", import.meta.url), "utf8");

// the planner's own code out of the page: top-level definitions, cut at their closing line
function grab(start, end = "\n}\n") {
  const i = html.indexOf("\n" + start);
  assert.ok(i >= 0, `site/index.html: "${start}" not found`);
  return html.slice(i, html.indexOf(end, i + 1) + end.length);
}
const code = [
  grab("const PROF_DE", "\n"), grab("const GATHER", "\n};\n"), grab("const items", "\n"), grab("const recipes", "\n"),
  grab("const byProduct", "\n"), grab("for(const r of recipes){ if(!byProduct", "\n"), grab("const I = ", "\n"),
  grab("const charsWith", "\n"), grab("const skillOf", "\n"),
  grab("function crafterFor("), grab("function pickRecipe("), grab("function gatherer(", "\n"),
  grab("function buildPlan("), grab("function listStructure("),
].join("\n");
// built once: running data.js (280 KB) per case would be slow; chars, shop and state are set per run
const W = new Function("chars", "shop", "state",
  `${data}\n${code}\nreturn { recipes, run(c, s, st) { chars = c; shop = s; state = st; return listStructure(); } };`)([], [], {});

// fixture characters: "Name|Prof=skill|…"; shop entries: "<Lua recipe index>*<qty>"
function plan(chars, shop) {
  const cs = chars.map((c, k) => {
    const [name, ...ps] = c.split("|");
    const skills = Object.fromEntries(ps.map(p => { const [prof, s] = p.split("="); return [prof, [Number(s), 300]]; }));
    return { id: k, name, profs: Object.keys(skills), skills };
  });
  const sh = shop.map(e => { const [n, qty] = e.split("*").map(Number); return { i: n - 1, qty }; });
  const out = W.run(cs, sh, { expandAll: false });
  return S.encodeList({ ...out, t: 0 });
}

function cases() {
  const out = []; let cur;
  for (const l of readFileSync(FIXTURE, "utf8").split("\n")) {
    if (!l.trim() || l.startsWith("#")) continue;
    const [word, ...rest] = l.split(" "), arg = rest.join(" ");
    if (word === "case") out.push(cur = { name: arg, chars: [], shop: [] });
    else if (word === "char") cur.chars.push(arg);
    else if (word === "shop") cur.shop.push(...arg.split(" "));
    else if (word === "expect") cur.expect = arg;
  }
  return out;
}

if (process.env.UPDATE) {
  // seeded, so a rewrite only changes what the planner changed
  let seed = 7;
  const rnd = n => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed % n; };
  const PROFS = ["Alchemie", "Schmiedekunst", "Verzauberkunst", "Ingenieurskunst", "Lederverarbeitung", "Schneiderei",
    "Bergbau", "Kräuterkunde", "Kürschnerei", "Kochkunst", "Erste Hilfe", "Angeln"];
  const NAMES = ["Ulfrik", "Bandor", "Ränka", "Mira"];
  const SKILLS = [1, 75, 150, 150, 225, 300];   // repeats, so equal skills (first character wins) occur
  const recipes = W.recipes;
  const lines = ["# Generated by UPDATE=1 node --test test/plan/ from the website's planner. Do not edit by hand.",
    "# char Name|Profession=skill|…   shop <recipe index, 1-based like Lua>*<quantity> …   expect <WB1 with t=0>", ""];
  for (let k = 1; k <= 80; k++) {
    const chars = [];
    for (let c = 0, n = 1 + rnd(3); c < n; c++) {
      const ps = new Set(); for (let p = 0, m = rnd(5); p < m; p++) ps.add(PROFS[rnd(PROFS.length)]);
      chars.push([NAMES[c], ...[...ps].map(p => `${p}=${SKILLS[rnd(SKILLS.length)]}`)].join("|"));
    }
    // mostly recipes of a profession somebody has, so crafting chains occur, not only AH rows
    const own = recipes.filter(r => chars.some(c => c.includes(`|${r.prof}=`)));
    const shop = [];
    for (let s = 0, n = 1 + rnd(3); s < n; s++) {
      const from = own.length && rnd(4) ? own : recipes;
      shop.push(`${from[rnd(from.length)].i + 1}*${1 + rnd(5)}`);
    }
    lines.push(`case ${k}`, ...chars.map(c => `char ${c}`), `shop ${shop.join(" ")}`, `expect ${plan(chars, shop)}`, "");
  }
  writeFileSync(FIXTURE, lines.join("\n"));
}

for (const c of cases()) {
  test(`plans.txt case ${c.name}`, () => assert.equal(plan(c.chars, c.shop), c.expect));
}
